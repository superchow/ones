import assert from 'node:assert/strict'

// Fictional bridge only. Compatible with Orca CLI eval/snapshot and browser runners.
export async function exerciseAiHours({ evaluate, wait }) {
  await evaluate('fixture.aiUnnumbered=true')
  const click = label => evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(label)}||b.getAttribute('aria-label')===${JSON.stringify(label)});if(!b||b.disabled)throw Error('Unavailable button');b.click()})()`)
  const check = label => evaluate(`(()=>{const field=[...document.querySelectorAll('label')].find(l=>l.textContent===${JSON.stringify(label)})?.querySelector('input');if(!field||field.disabled)throw Error('Unavailable checkbox');field.click()})()`)
  await check('已确认 ONES 与 Coho 均为本人账号')
  await click('读取考勤与已有工时')
  await wait(`document.body.innerText.includes('核对考勤依据')`)
  assert.equal(await evaluate(`document.querySelector('.hours-metrics').innerText.includes('8 小时')`), true)
  assert.equal(await evaluate(`document.body.innerText.includes('不存在时自动请求 Orca 创建')`), true)
  const sameRow = await evaluate(`(()=>{const buttons=[...document.querySelectorAll('button')];return buttons.find(b=>b.textContent==='AI 计算工时').parentElement===buttons.find(b=>b.textContent==='根据 Git 整理并计算工时').parentElement})()`)
  assert.equal(sameRow, true)
  await click('AI 计算工时')
  assert.equal(await evaluate(`calls.filter(c=>c.name==='hours.aiStart').length`), 0)
  await check('已核对本人当日上下班记录，无缺卡、跨日或外勤异常')
  await evaluate('fixture.holdAI=true')
  await click('AI 计算工时')
  await wait(`typeof releaseAI==='function'`)
  assert.equal(await evaluate(`document.body.innerText.includes('正在准备工时分析工作区并委托 AI')`), true)
  assert.equal(await evaluate(`[...document.querySelectorAll('.hours-calculate-actions button')].every(b=>b.disabled)`), true)
  await evaluate('(()=>{fixture.holdAI=false;releaseAI()})()')
  await wait(`document.body.innerText.includes('读取 AI 结果')`)
  assert.equal(await evaluate(`calls.filter(c=>c.name==='hours.aiStart').length`), 1)
  assert.equal(await evaluate(`calls.find(c=>c.name==='hours.aiStart').input.hashes.length`), 2)
  await click('读取 AI 结果')
  await wait(`document.body.innerText.includes('AI 尚未生成结果')`)
  await evaluate('fixture.aiReady=true')
  await click('读取 AI 结果')
  await wait(`document.body.innerText.includes('待确认工时')`)
  assert.equal(await evaluate(`document.getElementById('时长（分钟） #1').value`), '450')
  assert.equal(await evaluate(`document.getElementById('工作描述 #1').value`), '修复登录会话恢复')
  assert.equal(await evaluate(`[...document.querySelectorAll('details')].find(d=>d.querySelector('summary').textContent==='分析说明与未分配事项').open`), false)
  await evaluate(`(()=>{[...document.querySelectorAll('summary')].find(s=>s.textContent==='分析说明与未分配事项').click()})()`)
  assert.equal(await evaluate(`document.body.innerText.includes('无编号提交涉及登录模块')`), true)
  assert.equal(await evaluate(`[...document.querySelectorAll('details')].find(d=>d.querySelector('summary').textContent==='手动补充一笔工时').open`), false)
  const fill = value => evaluate(`(()=>{const field=document.getElementById('时长（分钟） #1');field.focus();field.value=${JSON.stringify(value)};field.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await fill('invalid')
  assert.equal(await evaluate(`document.getElementById('时长（分钟） #1').value`), 'invalid')
  assert.equal(await evaluate(`document.activeElement.id`), '时长（分钟） #1')
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='校验并预览').disabled`), true)
  await fill('300')
  assert.equal(await evaluate(`document.querySelector('.hours-footer').innerText.includes('5 小时')&&document.querySelector('.hours-footer').innerText.includes('2.5 小时')`), true)
  await fill('450')
  const choose = (label, value) => evaluate(`(()=>{const field=document.getElementById(${JSON.stringify(label)});if(!field||field.disabled)throw Error('Unavailable select: '+${JSON.stringify(label)});if(field.classList.contains('search-select-trigger')){field.click();const choice=[...field.closest('.search-select').querySelectorAll('[role="option"]')].find(o=>o.dataset.value===${JSON.stringify(value)});if(!choice)throw Error('Missing choice');choice.click()}else{field.value=${JSON.stringify(value)};field.dispatchEvent(new Event('change',{bubbles:true}))}})()`)
  await choose('关联任务 / Bug #1', 'bug-fixture')
  await click('校验并预览')
  await wait(`document.body.innerText.includes('提交预览')`)
  assert.equal(await evaluate(`calls.filter(c=>c.name==='hours.preview').at(-1).input.allocations[0].taskId`), 'bug-fixture')
  await evaluate(`(()=>{const field=document.getElementById('工作描述 #1');field.focus();field.value='修复登录会话恢复并完善校验';field.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  assert.equal(await evaluate(`document.body.innerText.includes('提交预览')`), false)
  await click('校验并预览')
  await wait(`document.body.innerText.includes('提交预览')`)
  await evaluate('fixture.aiReady=false')
  await click('读取 AI 结果')
  await wait(`document.body.innerText.includes('AI 尚未生成结果')`)
  assert.equal(await evaluate(`document.body.innerText.includes('提交预览')`), true)
  await evaluate('fixture.aiReady=true')
  await evaluate('fixture.aiNewTask=true')
  await click('读取 AI 结果')
  await wait(`document.body.innerText.includes('新任务标题 #1')`)
  await click('读取项目与创建字段')
  await wait(`document.body.innerText.includes('新任务所属迭代 #1')`)
  await choose('新任务所属项目 #1', 'other-project')
  await wait(`document.getElementById('新任务所属迭代 #1')?.querySelector('option[value="other-project-next"]')`)
  await choose('新任务所属迭代 #1', 'other-project-next')
  await click('校验并预览')
  await wait(`document.body.innerText.includes('提交预览')`)
  const edited = await evaluate(`calls.filter(c=>c.name==='hours.preview').at(-1).input.allocations[0].newTask`)
  assert.equal(edited.projectId, 'other-project'); assert.equal(edited.sprintId, 'other-project-next')
  await click('根据 Git 整理并计算工时')
  await wait(`document.getElementById('关联任务 / Bug #1')?.value==='task-fixture'`)
  const bugId = await evaluate(`(()=>{const field=document.getElementById('关联任务 / Bug #1');field.click();const id=[...field.closest('.search-select').querySelectorAll('[role="option"]')].find(o=>o.dataset.value&&o.dataset.value!=='__new__').dataset.value;field.click();return id})()`)
  await choose('关联任务 / Bug #1', bugId)
  await click('校验并预览')
  await wait(`document.body.innerText.includes('提交预览')`)
  assert.equal(await evaluate(`calls.filter(c=>c.name==='hours.preview').at(-1).input.allocations[0].taskId`), bugId)
  await choose('关联任务 / Bug #1', '__new__')
  await wait(`document.body.innerText.includes('新任务标题 #1')&&!app.busy`)
  await choose('新任务所属项目 #1', 'project')
  await wait(`document.getElementById('新任务所属迭代 #1')&&!app.busy`)
  await choose('新任务所属迭代 #1', 'project-sprint')
  await click('校验并预览')
  await wait(`document.body.innerText.includes('将新建任务')`)
  assert.equal(await evaluate(`calls.filter(c=>c.name==='hours.submit').length`), 0)
  await click('展开本地 Git 整理')
  await click('清空提交选择')
  await click('读取 AI 结果')
  assert.equal(await evaluate(`document.body.innerText.includes('Git 范围已变化')`), true)
  return { sameRow, aiRequests: 1, analyzedCommits: 2, draftMinutes: 450, editableExistingBothModes: true, editableNewProjectAndIteration: true, explicitWorkspaceProgress: true, pendingPreservesPreview: true, liveTotalsAndInvalidInput: true, detailsCollapsed: true, changedScopeRejected: true, writes: 0 }
}
