import assert from 'node:assert/strict'

export async function exerciseTaskSearch({ evaluate, wait }) {
  await wait(`!!app.status&&!app.busy`)
  await evaluate(`(()=>{app.hours.tasks=Array.from({length:150},(_,i)=>({id:'t'+i,number:2000+i,name:'修复登录与恢复 '+i,project:{id:i%2?'other-project':'project',name:i%2?'平台项目':'社区项目'},issueType:{id:'bug',name:'Bug'},status:{id:'open',name:'Open'}}));app.hours.allocations=[{taskId:'t0',start:'09:00',minutes:60,description:'已确认的工作描述'}];app.hours.taskLoaded=true;app.hours.manualExpanded=true;app.render()})()`)
  const open = label => evaluate(`document.getElementById(${JSON.stringify(label)}).click()`)
  const search = term => evaluate(`(()=>{const q=document.querySelector('.search-select-popup input');q.value=${JSON.stringify(term)};q.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  const key = key => evaluate(`document.querySelector('.search-select-popup input').dispatchEvent(new KeyboardEvent('keydown',{key:${JSON.stringify(key)},bubbles:true}))`)
  const results = () => evaluate(`[...document.querySelectorAll('.search-select-options [role="option"]')].map(o=>o.dataset.value)`)
  await open('关联任务 / Bug #1')
  assert.equal(await evaluate(`document.querySelector('.search-select-count').textContent.includes('150')`), true)
  await search('平台 149')
  assert.deepEqual(await results(), ['t149', '__new__'])
  assert.equal(await evaluate(`app.hours.allocations[0].taskId`), 't0')
  await search('不存在的任务')
  await key('Enter')
  assert.equal(await evaluate(`!!app.hours.allocations[0].newTask`), false)
  await key('Escape')
  assert.equal(await evaluate(`!!document.querySelector('.search-select-popup')`), false)
  assert.equal(await evaluate(`app.hours.allocations[0].taskId`), 't0')
  await open('关联任务 / Bug #1')
  await search('#2149')
  await key('ArrowDown')
  await key('Enter')
  assert.equal(await evaluate(`app.hours.allocations[0].taskId`), 't149')
  assert.equal(await evaluate(`document.querySelector('.hours-project-meta').textContent.includes('平台项目')`), true)
  assert.equal(await evaluate(`app.hours.allocations[0].minutes`), 60)
  await open('目标任务 / Bug')
  await search('社区 2')
  await search('#2002')
  await key('Enter')
  assert.equal(await evaluate(`app.hours.selected`), 't2')
  await open('关联任务 / Bug #1')
  await search('没有关联项')
  await evaluate(`document.querySelector('.search-select-options [data-value="__new__"]').click()`)
  await wait(`!!document.getElementById('新任务标题 #1')&&!app.busy`)
  assert.equal(await evaluate(`app.hours.allocations[0].newTask.title`), '已确认的工作描述')
  return { searchesAllLoaded150Tasks: true, numberAndProjectSearch: true, keyboardSelection: true, escapePreservesSelection: true, noMatchDoesNotAutoCreate: true, manualEntrySearch: true, createFromNoMatch: true }
}
