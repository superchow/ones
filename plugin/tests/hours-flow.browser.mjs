import assert from 'node:assert/strict'

// Run against hours-fixture-server.mjs only. All business responses are fictional.
export async function exerciseHoursFlow(page) {
  await page.goto('http://127.0.0.1:18779')
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const button = name => page.getByRole('button', { name, exact: true })
  const punchConfirmation = () => page.getByRole('checkbox', { name: '已核对本人当日上下班记录，无缺卡、跨日或外勤异常', exact: true })
  const read = async () => {
    await button('读取考勤与已有工时').click()
    await page.getByRole('heading', { name: '核对考勤依据', exact: true }).waitFor()
  }
  const count = name => page.evaluate(name => calls.filter(c => c.name === name).length, name)
  await page.getByRole('checkbox', { name: '已确认 ONES 与 Coho 均为本人账号', exact: true }).click()
  await read()
  assert.equal(await page.getByRole('combobox', { name: '上班打卡', exact: true }).inputValue(), '1')
  assert.equal(await page.getByRole('combobox', { name: '下班打卡', exact: true }).inputValue(), '0')
  assert.equal(await punchConfirmation().isChecked(), false)
  assert.equal(await count('tasks.list'), 0)
  await button('根据 Git 整理并计算工时').click()
  assert.match(await page.getByRole('alert').innerText(), /勾选/)
  assert.equal(await count('git.read'), 0)
  await punchConfirmation().click()
  await button('根据 Git 整理并计算工时').click()
  await page.getByRole('heading', { name: '待确认工时', exact: true }).waitFor()
  assert.equal(await page.getByRole('textbox', { name: '时长（分钟） #1', exact: true }).inputValue(), '450')
  assert.equal(await count('git.read'), 1)
  assert.equal(await count('tasks.list'), 1)
  await button('校验并预览').click()
  await page.getByRole('heading', { name: '提交预览', exact: true }).waitFor()
  assert.equal(await button('确认提交到 ONES').isEnabled(), false)

  await page.evaluate(() => { fixture.times = ['21:20', '08:58']; fixture.existing = 0 })
  await read()
  assert.equal(await punchConfirmation().isChecked(), false)
  await punchConfirmation().click()
  await page.waitForFunction(() => document.querySelector('.hours-metrics')?.innerText.includes('10 小时'))
  await button('根据 Git 整理并计算工时').click()
  await page.waitForFunction(() => document.getElementById('时长（分钟） #1')?.value === '600')
  assert.equal(await page.getByRole('textbox', { name: '开始时间 #1', exact: true }).inputValue(), '08:58')

  // Explicitly clearing all commits must not silently select them again.
  await button('展开本地 Git 整理').click()
  await button('清空提交选择').click()
  const gitCount = await count('git.read')
  await button('根据 Git 整理并计算工时').click()
  assert.match(await page.getByRole('alert').innerText(), /没有选中的 Git 提交/)
  assert.equal(await count('git.read'), gitCount)
  await button('全选提交').click()

  // Late attendance still reports the exact rule failure instead of a grey button.
  await page.evaluate(() => { fixture.times = ['09:15', '20:00'] })
  await read()
  await punchConfirmation().click()
  await button('根据 Git 整理并计算工时').click()
  assert.match(await page.getByRole('alert').innerText(), /时段不在已确认工时规则/)
  await page.evaluate(() => { fixture.times = ['09:00', '12:00', '18:30'] })
  await read()
  assert.equal(await page.getByRole('combobox', { name: '上班打卡', exact: true }).inputValue(), '')
  assert.equal(await page.getByRole('combobox', { name: '下班打卡', exact: true }).inputValue(), '')

  await page.evaluate(() => { fixture.times = ['08:58', '21:20']; fixture.existing = 600 })
  await read()
  await punchConfirmation().click()
  await button('根据 Git 整理并计算工时').click()
  assert.match(await page.getByRole('alert').innerText(), /无剩余可填/)
  await page.evaluate(() => { fixture.existing = 0; fixture.enabled = false; return app.gitProjects.load() })
  await read()
  await punchConfirmation().click()
  await button('根据 Git 整理并计算工时').click()
  assert.match(await page.getByRole('alert').innerText(), /启用至少一个/)
  await button('管理 Git 关联').first().click()
  await page.getByRole('heading', { name: 'Git 项目关联', exact: true }).waitFor()
  await page.getByRole('tab', { name: '考勤工时', exact: true }).click()

  // Reproduce startup failure; calculation retries project loading.
  await page.evaluate(() => { fixture.enabled = true; fixture.failProjects = true; app.gitProjects.loaded = false; return app.gitProjects.load() })
  await page.evaluate(() => { fixture.failProjects = false; fixture.holdProjects = true; void app.gitProjects.load() })
  const beforeLoad = await count('git.projects.load')
  await button('根据 Git 整理并计算工时').click()
  assert.equal(await button('根据 Git 整理并计算工时').isEnabled(), false)
  await page.evaluate(() => { fixture.holdProjects = false; releaseProjects() })
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === '根据 Git 整理并计算工时' && !b.disabled))
  assert.equal(await count('git.projects.load'), beforeLoad)
  assert.equal(await page.getByRole('alert').count(), 0)
  assert.equal(await page.getByRole('textbox', { name: '时长（分钟） #1', exact: true }).inputValue(), '600')
  // Missing punch correction uses the total day, subtracts existing hours,
  // resets confirmation on edits, and labels the preview source.
  await page.evaluate(() => { fixture.times = ['09:00']; fixture.existing = 30 })
  await read()
  await page.getByRole('checkbox', { name: '手动输入当日工时', exact: true }).click()
  const manualConfirmation = () => page.getByRole('checkbox', { name: '已确认手动输入的是本人当日实际工作总时长', exact: true })
  const manualHours = () => page.getByRole('spinbutton', { name: '当日工作总时长（小时）', exact: true })
  await manualHours().fill('8')
  assert.equal(await manualConfirmation().isChecked(), false)
  await manualConfirmation().click()
  await button('根据 Git 整理并计算工时').click()
  await page.waitForFunction(() => document.getElementById('时长（分钟） #1')?.value === '450')
  await button('校验并预览').click()
  await page.getByText('额度依据：手动确认当日工作总时长', { exact: true }).waitFor()
  await manualHours().fill('9')
  assert.equal(await manualConfirmation().isChecked(), false)
  assert.equal(await page.getByRole('heading', { name: '提交预览', exact: true }).count(), 0)
  await page.getByRole('checkbox', { name: '手动输入当日工时', exact: true }).click()
  assert.equal(await punchConfirmation().isChecked(), false)
  await page.evaluate(() => { fixture.times = []; fixture.existing = 30 })
  await read()
  await page.getByRole('checkbox', { name: '手动输入当日工时', exact: true }).click()
  await manualHours().fill('8')
  await manualConfirmation().click()
  await button('根据 Git 整理并计算工时').click()
  await page.waitForFunction(() => document.getElementById('时长（分钟） #1')?.value === '450')
  assert.equal(await count('hours.submit'), 0)
  assert.deepEqual(errors, [])
  return { automaticPunches: true, actualTimeRangeMinutes: 600, delayedProjectLoadRecovered: true,
    emptySelectionPreserved: true, missingPunchManualCorrection: true, businessWrites: 0, pageErrors: errors,
    requestCounts: await page.evaluate(() => Object.fromEntries(['day.read','git.projects.load','git.read','tasks.list','hours.preview','hours.submit'].map(name => [name,calls.filter(c => c.name === name).length]))) }
}
