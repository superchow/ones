import assert from 'node:assert/strict'

export async function exerciseHoursInteraction({ evaluate, wait }) {
  const click = label => evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(label)});if(!b||b.disabled)throw Error('Unavailable button');b.click()})()`)
  const check = label => evaluate(`(()=>{const field=[...document.querySelectorAll('label')].find(l=>l.textContent===${JSON.stringify(label)})?.querySelector('input');if(!field||field.disabled)throw Error('Unavailable checkbox');field.click()})()`)
  const fill = (id, value) => evaluate(`(()=>{const field=document.getElementById(${JSON.stringify(id)});field.focus();field.value=${JSON.stringify(value)};field.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  assert.equal(await evaluate(`[...document.querySelectorAll('.hours-calculate-actions button')].every(b=>b.disabled)`), true)
  await evaluate(`(()=>{fixture.times=['09:00'];fixture.existing=30})()`)
  await check('已确认 ONES 与 Coho 均为本人账号')
  await click('读取考勤与已有工时')
  await wait(`document.body.innerText.includes('核对考勤依据')&&!app.busy`)
  assert.equal(await evaluate(`!!document.querySelector('.hours-source-summary')`), true)
  assert.equal(await evaluate(`calls.filter(c=>c.name==='tasks.list').length`), 0)
  await check('手动输入当日工时')
  await fill('当日工作总时长（小时）', '8')
  assert.equal(await evaluate(`document.querySelector('.hours-metrics').innerText.includes('7.5 小时')`), true)
  await check('已确认手动输入的是本人当日实际工作总时长')
  await click('根据 Git 整理并计算工时')
  await wait(`document.getElementById('时长（分钟） #1')?.value==='450'&&!app.busy`)
  await fill('时长（分钟） #1', '999')
  assert.equal(await evaluate(`document.querySelector('.hours-footer').innerText.includes('超出')`), true)
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='校验并预览').disabled`), true)
  await fill('时长（分钟） #1', '300')
  await click('校验并预览')
  await wait(`document.body.innerText.includes('额度依据：手动确认当日工作总时长')`)
  await fill('当日工作总时长（小时）', '9')
  assert.equal(await evaluate(`document.body.innerText.includes('提交预览')`), false)
  const before = await evaluate(`calls.filter(c=>c.name==='git.read').length`)
  await click('根据 Git 整理并计算工时')
  assert.equal(await evaluate(`calls.filter(c=>c.name==='git.read').length`), before)
  await evaluate(`(()=>{fixture.times=['21:20','08:58'];fixture.existing=0})()`)
  await click('读取考勤与已有工时')
  await wait(`document.getElementById('上班打卡')?.value==='1'&&!app.busy`)
  assert.equal(await evaluate(`document.querySelector('.hours-metrics').innerText.includes('10 小时')`), true)
  await check('已核对本人当日上下班记录，无缺卡、跨日或外勤异常')
  await click('调整日期与账号')
  assert.equal(await evaluate(`document.getElementById('业务日期（YYYY-MM-DD）').classList.contains('date-trigger')`), true)
  await click('读取考勤与已有工时')
  await wait(`document.querySelector('.hours-source-summary')&&!app.busy`)
  await check('已核对本人当日上下班记录，无缺卡、跨日或外勤异常')
  assert.equal(await evaluate(`calls.filter(c=>c.name==='hours.submit').length`), 0)
  return { compactDaySummary: true, manualMissingPunch: true, totalUpdates: true, overBudgetBlocked: true, editRevokesPreview: true, dateControl: true, normalDayMinutes: 600, writes: 0 }
}
